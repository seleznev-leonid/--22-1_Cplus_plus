#include <iostream>  // Подключаем библиотеку для ввода/вывода
using namespace std; // Используем стандартное пространство имён

int main() // Главная функция программы
{
    int x = 3, y = 4; // Создаём переменные x (со значением 3) и y (со значением 4)
    
    // Выводим:
    // ++x - увеличенный на 1 x (сначала увеличиваем, потом выводим - будет 4)
    // --y - уменьшенный на 1 y (сначала уменьшаем, потом выводим - будет 3)
    cout << ++x << "\t" << --y << endl;
    
    // Выводим:
    // x++ - текущее значение x (4), потом увеличиваем на 1
    // y-- - текущее значение y (3), потом уменьшаем на 1
    cout << x++ << "\t" << y-- << endl;
    
    // Выводим текущие значения:
    // x теперь 5 (после увеличения в предыдущей строке)
    // y теперь 2 (после уменьшения в предыдущей строке)
    cout << x << "\t" << y << endl;
    
    return 0; // Завершаем программу
}
