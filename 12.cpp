#include <iostream>  // Подключаем библиотеку для ввода/вывода
using namespace std; // Используем стандартное пространство имён

// Функция sum принимает два целых числа (x и y) и возвращает их сумму
int sum(int x, int y) 
{
    return x + y; // Возвращаем результат сложения
}

int main() // Главная функция программы
{
    int a = 5, b = 3, c; // Создаём переменные: a=5, b=3, c (пока без значения)

    // 1 - Вызов функции sum, сохранение результата в переменную c
    c = sum(a, b); // sum(5, 3) вернёт 8, и это значение запишется в c
    cout << "sum = " << c << endl; // Выведет: sum = 8

    // 2 - Вызов функции sum прямо внутри cout (без сохранения в переменную)
    cout << "sum = " << sum(a, b) << endl; // Тоже выведет: sum = 8

    return 0; // Завершаем программу
}
