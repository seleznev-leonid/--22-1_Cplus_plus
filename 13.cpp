#include <iostream>  // Подключаем библиотеку для ввода/вывода
using namespace std; // Используем стандартное пространство имён

// Объявление функции max (прототип)
// Говорим компилятору, что такая функция будет определена позже
float max(float x, float y);

int main() // Главная функция программы
{
    float a = 5.5, b = 3.2, c = 14.1, d; // Объявляем переменные типа float
    
    // 1 - Находим максимальное из трёх чисел:
    // Сначала max(a,b) найдёт большее между a и b,
    // затем результат сравнивается с c
    d = max(max(a,b), c);
    
    cout << "max = " << d << endl; // Выводим результат
    return 0; // Завершаем программу
}

// Определение функции max
// Возвращает большее из двух чисел x и y
float max(float x, float y)
{
    // Используем тернарный оператор:
    // если x > y, возвращаем x, иначе - y
    return (x > y) ? x : y;
}
